    private static readonly Dictionary<string, Definition> Cache = new();

    public static Definition? Get(string? name)
    {
        if (name == null)
            return null;
        if (Cache.TryGetValue(name, out var cached))
            return cached;

        Definition? def = null;
        if (Stroked.TryGetValue(name, out var s))
            def = new Definition(Geometry.Parse(s.Data), s.Stroke, 16, Filled: false);
        else if (Filled.TryGetValue(name, out var f))
            def = new Definition(Geometry.Parse(f), 0, 24, Filled: true);
        if (def != null)
            Cache[name] = def;
        return def;
    }

    public static IEnumerable<string> Names => Stroked.Keys.Concat(Filled.Keys);
